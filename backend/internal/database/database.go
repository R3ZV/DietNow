package database

import (
	"fmt"
	"os"
	"strconv"
	"time"

	"gorm.io/driver/postgres"
	"gorm.io/gorm"
	"gorm.io/gorm/logger"
)

// Config holds everything needed to open a pooled connection. Build it from the
// environment with ConfigFromEnv (the same DB_* vars docker-compose.yml uses).
type Config struct {
	Host     string
	Port     string
	User     string
	Password string
	Name     string
	SSLMode  string

	MaxOpenConns    int
	MaxIdleConns    int
	ConnMaxLifetime time.Duration
	LogLevel        logger.LogLevel
}

// ConfigFromEnv reads DB_* variables, applying safe defaults for local dev.
func ConfigFromEnv() Config {
	LoadDotEnv()
	return Config{
		Host:            env("DB_HOST", "localhost"),
		Port:            env("DB_PORT", "5432"),
		User:            env("DB_USER", "dietnow"),
		Password:        env("DB_PASSWORD", "dietnow_dev_pw"),
		Name:            env("DB_NAME", "dietnow"),
		SSLMode:         env("DB_SSLMODE", "disable"),
		MaxOpenConns:    envInt("DB_MAX_OPEN_CONNS", 20),
		MaxIdleConns:    envInt("DB_MAX_IDLE_CONNS", 10),
		ConnMaxLifetime: time.Duration(envInt("DB_CONN_MAX_LIFETIME_MIN", 60)) * time.Minute,
		LogLevel:        parseLogLevel(env("DB_LOG_LEVEL", "warn")),
	}
}

// DSN renders the PostgreSQL connection string.
//
// We pin TimeZone=UTC for the connection. Note this only affects how timestamptz
// values are rendered; our calendar fields are zone-less DATE columns, so they
// are unaffected either way — this is just belt-and-suspenders for CreatedAt/etc.
func (c Config) DSN() string {
	return fmt.Sprintf(
		"host=%s port=%s user=%s password=%s dbname=%s sslmode=%s TimeZone=UTC",
		c.Host, c.Port, c.User, c.Password, c.Name, c.SSLMode,
	)
}

// Connect opens the connection, configures the pool, and verifies it with a ping.
func Connect(cfg Config) (*gorm.DB, error) {
	db, err := gorm.Open(postgres.Open(cfg.DSN()), &gorm.Config{
		Logger: logger.Default.LogMode(cfg.LogLevel),
		// Timestamps are generated by the DB clock (UTC) for consistency.
		NowFunc: func() time.Time { return time.Now().UTC() },
	})
	if err != nil {
		return nil, fmt.Errorf("open database: %w", err)
	}

	sqlDB, err := db.DB()
	if err != nil {
		return nil, fmt.Errorf("access underlying sql.DB: %w", err)
	}
	sqlDB.SetMaxOpenConns(cfg.MaxOpenConns)
	sqlDB.SetMaxIdleConns(cfg.MaxIdleConns)
	sqlDB.SetConnMaxLifetime(cfg.ConnMaxLifetime)

	if err := sqlDB.Ping(); err != nil {
		return nil, fmt.Errorf("ping database: %w", err)
	}
	return db, nil
}

func env(key, def string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return def
}

func envInt(key string, def int) int {
	if v := os.Getenv(key); v != "" {
		if n, err := strconv.Atoi(v); err == nil {
			return n
		}
	}
	return def
}

func parseLogLevel(s string) logger.LogLevel {
	switch s {
	case "silent":
		return logger.Silent
	case "error":
		return logger.Error
	case "info":
		return logger.Info
	default:
		return logger.Warn
	}
}
